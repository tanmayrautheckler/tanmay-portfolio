export const DEFAULT_PALETTE = "barcelona";
export const paletteIds: readonly string[] = clubPalettes.map(palette => palette.id);
export const paletteAliases: Record<string, string> = { cyan: "barcelona", ember: "united", ocean: "madrid", luxe: "madrid", citrus: "barcelona", guava: "united", lagoon: "bayern", iris: "madrid" };
export const paletteClasses = [...paletteIds, ...Object.keys(paletteAliases)];
export function validPalette(value: string | null): string { return value && paletteIds.includes(value) ? value : (value && paletteAliases[value]) || DEFAULT_PALETTE; }
function rgb(hex: string) { return hex.match(/[\da-f]{2}/gi)!.map(part => parseInt(part, 16)).join(", "); }
export const paletteStyles = clubPalettes.map(palette => (["light", "dark"] as const).map(mode => {
  const p = palette[mode];
  const onHighlight = mode === "light" ? palette.light.foreground : palette.dark.background;
  return `.theme-${palette.id}${mode === "light" ? ":not(.dark)" : ".dark"}{--background:${p.background};--foreground:${p.foreground};--surface:${p.surface};--surface-hover:${p.hover};--text-secondary:${p.muted};--border:${p.border};--accent:${p.accent};--accent-rgb:${rgb(p.accent)};--accent-hover:${p.accentHover};--accent-glow:rgba(${rgb(p.accent)},.07);--success:${p.success};--palette-highlight:${p.highlight};--palette-secondary:${p.secondary};--palette-on-highlight:${onHighlight};--gradient-1:${p.accent};--gradient-2:${p.accentHover};--gradient-3:${p.foreground};--gradient-4:${p.foreground};--selection-bg:${p.highlight};--selection-ink:${onHighlight};}`;
}).join("\n")).join("\n");
